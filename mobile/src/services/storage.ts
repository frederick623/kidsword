import { Preferences } from "@capacitor/preferences";

/** Minimal async key/value persistence used by the game service. */
export interface KeyValueStore {
  get(key: string): Promise<string | null>;
  set(key: string, value: string): Promise<void>;
  remove(key: string): Promise<void>;
}

/**
 * Native persistent storage: SharedPreferences (Android) / UserDefaults (iOS),
 * falling back to localStorage in the browser. Survives app restarts and is
 * not evicted under storage pressure like WebView localStorage can be.
 */
export class PreferencesStore implements KeyValueStore {
  async get(key: string): Promise<string | null> {
    const { value } = await Preferences.get({ key });
    return value;
  }

  async set(key: string, value: string): Promise<void> {
    await Preferences.set({ key, value });
  }

  async remove(key: string): Promise<void> {
    await Preferences.remove({ key });
  }
}

/** In-memory store for unit tests. */
export class MemoryStore implements KeyValueStore {
  private readonly data = new Map<string, string>();

  async get(key: string): Promise<string | null> {
    return this.data.get(key) ?? null;
  }

  async set(key: string, value: string): Promise<void> {
    this.data.set(key, value);
  }

  async remove(key: string): Promise<void> {
    this.data.delete(key);
  }
}
